    private void integerMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_integerMouseClicked
       
        if (in.isEmpty()) {
        in = "-";
        eq += "-";
    } else {
        if (in.startsWith("-")) {
            in = in.substring(1);
        } else {
            in = "-" + in;
        }

        int i = eq.length() - 1;

        while (i >= 0 && (Character.isDigit(eq.charAt(i)) || eq.charAt(i) == '.')) {
            i--;
        }

        eq = eq.substring(0, i + 1) + in;
    }

    text.setText(eq);
        
    }//GEN-LAST:event_integerMouseClicked

