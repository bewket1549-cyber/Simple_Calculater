    private boolean isOperator(char c) {
    return c == '+' || c == '-' || c == '*' || c == '/';
}
    
    private double evaluateSimple(String expr) {
    double[] numbers = new double[50];
    char[] ops = new char[50];
    int ni = 0, oi = 0;
    String num = "";

    for (int i = 0; i < expr.length(); i++) {
        char c = expr.charAt(i);

        if (Character.isDigit(c) || c == '.' || (c == '-' && num.isEmpty())) {
            num += c;
        } else {
            numbers[ni++] = Double.parseDouble(num);
            num = "";
            ops[oi++] = c;
        }
    }
    numbers[ni++] = Double.parseDouble(num);

    for (int i = 0; i < oi; i++) {
        if (ops[i] == '*' || ops[i] == '/') {
            if (ops[i] == '*') {
                numbers[i] *= numbers[i + 1];
            } else {
                if (numbers[i + 1] == 0) throw new ArithmeticException();
                numbers[i] /= numbers[i + 1];
            }

            for (int j = i + 1; j < ni - 1; j++) numbers[j] = numbers[j + 1];
            for (int j = i; j < oi - 1; j++) ops[j] = ops[j + 1];

            ni--;
            oi--;
            i--;
        }
    }

    double result = numbers[0];

    for (int i = 0; i < oi; i++) {
        if (ops[i] == '+') result += numbers[i + 1];
        else result -= numbers[i + 1];
    }

    return result;
}
    
